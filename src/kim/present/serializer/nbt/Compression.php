declare(strict_types=1);

namespace kim\present\serializer\nbt;

/** Compression formats supported by {@see NbtSerializer::toCompressed()} */
enum Compression{
    /** RFC 1952 gzip (`gzencode`), used by Java Edition .nbt / .dat files */
    case GZIP;
    /** RFC 1950 zlib (`gzcompress`) */
    case ZLIB;
    /** RFC 1951 raw deflate (`gzdeflate`), the smallest output */
    case DEFLATE;
}
